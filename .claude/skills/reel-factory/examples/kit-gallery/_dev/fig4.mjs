import { createCanvas } from '@napi-rs/canvas';
import fs from 'fs';
import { createFigure, LIGHTS } from '../../../lib/kit/figures/index.mjs';
const W=1400,H=720; const c=createCanvas(W,H), x=c.getContext('2d');
x.fillStyle='#c9c3b4'; x.fillRect(0,0,W,H); x.fillStyle='#a89f88'; x.fillRect(0,640,W,80);
const kid=createFigure({age:'child',outfit:'uniform',seed:3}), man=createFigure({age:'adult',outfit:'kurta',seed:5}), ald=createFigure({age:'elder',outfit:'kurta',seed:7,glasses:true}), g=createFigure({age:'child',outfit:'uniform',seed:3,variant:'ghost'});
const poses=['walk','reach','crouch','turn','cower'];
const L=LIGHTS.lamp;
poses.forEach((p,i)=>{ const f=i%2?man:kid; f.draw(x,{x:120+i*200,feet:690,height:i%2?480:400,pose:p==='turn'?{name:'turn',turn:0.55}:p,t:0.4,phase:i,light:i<3?LIGHTS.noon:LIGHTS.lamp,gaze:[0.8,0]}); });
ald.draw(x,{x:1130,feet:690,height:470,pose:'walk',t:0.7,light:LIGHTS.noon});
g.draw(x,{x:1300,feet:690,height:420,pose:'stand',t:0.7,light:LIGHTS.noon});
fs.writeFileSync(process.argv[2],c.toBuffer('image/png'));
